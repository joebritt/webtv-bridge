#!/usr/bin/env node
// What the bridge firmware carries from the JS side (WEBTV_LPT_BRIDGE.md §10.6, §10.7), as C:
//   pico/src/gen/sb_assets.h, sb_assets.c   the stock-box loader (as stage 0 receives it), stage 0,
//                                           the tier-3 image, the loader addresses core 0 calls, and
//                                           the updater: the same loader built at UPDATER_BASE, which
//                                           rewrites the tier-3 area whatever loader version is running
//   pico/src/gen/sb_patches.bin             the patch table (src/stockbox/patches.json.gz), binary,
//                                           pulled in by sb_patches.S with .incbin
//
//   node tools/picogen.mjs
//
// sb_patches.bin, all big-endian:
//   'LPTP' version:4 count:4 then count entries of 48 bytes, sorted by (code, size, fs):
//     code:4 size:4 fs:4 flags:4 (bit 0: the build has a ROM filesystem; bit 1: it takes keys over
//     PARMOD, into its IR input ring) after_code:4 after_fs:4
//     runs:4 (byte offset of the build's runs from the start) name:4 (byte offset of its name)
//     ir_off:4 ir_word:4 power_off:4 power_word:4 (the words the bridge's settings change, as
//     byte offsets into the image and the words there after the patch; offset 0 = none)
//   runs: per build, nruns:4, then per run offset:4 nwords:4 words
//   names: NUL-terminated
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { buildLoader, buildStage0, LOADER_BASE, SCRATCH } from '../src/stockbox/loader.js';
import { buildTier3, TIER3_LBA, TIER3_BASE } from '../src/stockbox/tier3.js';
import { PATCH_TABLE_VERSION } from '../src/stockbox/patchtable.js';

const OUT = 'pico/src/gen';
mkdirSync(OUT, { recursive: true });
const hex = (v) => '0x' + (v >>> 0).toString(16).padStart(8, '0');
const bytesC = (name, b) => `const uint8_t ${name}[${b.length}] = {\n${Array.from({ length: Math.ceil(b.length / 16) }, (_, i) =>
  '  ' + Array.from(b.subarray(i * 16, i * 16 + 16), (x) => `0x${x.toString(16).padStart(2, '0')},`).join(' ')).join('\n')}\n};\n`;

const loader = buildLoader(), stage0 = buildStage0(), tier3 = buildTier3({ loader });
// the updater runs from 0xa0500000: free while the loader runs (an OS is read there only later),
// clear of the tier-3 image the boot ROM left at 0x80400000 (6 KB) and of the buffers after it
const UPDATER_BASE = 0xa0500000, UPDATER_BUF = 0xa0520000, UPDATER_BUF2 = 0xa0530000;
const updater = buildLoader({ base: UPDATER_BASE });
const U = (n) => hex(updater.labels.get(n));
const sent = loader.bytes.subarray(0, loader.labels.get('V_SCALE') - loader.base); // the loader sets its own variables
const L = (n) => hex(loader.labels.get(n));

writeFileSync(`${OUT}/sb_assets.h`, `// Generated by tools/picogen.mjs from src/stockbox/ (do not edit).
#pragma once
#include <stdint.h>
#include <stddef.h>

#define SB_LOADER_BASE   ${hex(LOADER_BASE)}u
#define SB_SCRATCH       ${hex(SCRATCH)}u
#define SB_DISK_READ     ${L('disk_read')}u
#define SB_DISK_WRITE    ${L('disk_write')}u
#define SB_SUM_WORDS     ${L('sum_words')}u
#define SB_BOOT_RAM      ${L('boot_ram')}u
#define SB_STAGE0_BASE   ${hex(stage0.base)}u

// the tier-3 area (tier3.js): where test 19 reads it from, and where the boot ROM put it in RAM
#define SB_TIER3_LBA     ${TIER3_LBA}u
#define SB_TIER3_RAM     ${hex(TIER3_BASE)}u
// the updater (the loader built at SB_UPD_BASE) and its buffers
#define SB_UPD_BASE      ${hex(UPDATER_BASE)}u
#define SB_UPD_DISK_READ ${U('disk_read')}u
#define SB_UPD_DISK_WRITE ${U('disk_write')}u
#define SB_UPD_BUF       ${hex(UPDATER_BUF)}u
#define SB_UPD_BUF2      ${hex(UPDATER_BUF2)}u

extern const uint8_t sb_loader[${sent.length}];     // the loader as stage 0 takes it (its variables left out)
extern const uint8_t sb_stage0[${stage0.size}];     // typed into RAM with \`sl\` at SB_STAGE0_BASE
extern const uint8_t sb_tier3[${tier3.length}];     // the loader as a tier-3 image (tier3.js)
extern const uint8_t sb_updater[${updater.bytes.length}];   // the loader built at SB_UPD_BASE

// the patch table (sb_patches.S, .incbin of sb_patches.bin)
extern const uint8_t sb_patches[];
extern const uint8_t sb_patches_end[];
`);
writeFileSync(`${OUT}/sb_assets.c`, `// Generated by tools/picogen.mjs from src/stockbox/ (do not edit).
#include "sb_assets.h"

${bytesC('sb_loader', sent)}
${bytesC('sb_stage0', stage0.bytes)}
${bytesC('sb_tier3', tier3)}
${bytesC('sb_updater', updater.bytes)}`);

// ---- the patch table
const table = JSON.parse(gunzipSync(readFileSync('src/stockbox/patches.json.gz')));
const entries = Object.entries(table.builds).map(([key, b]) => {
  const [code, size, fs] = key.split('-');
  return { code: parseInt(code, 16) >>> 0, size: parseInt(size, 16) >>> 0, fs: fs === 'nofs' ? 0 : parseInt(fs, 16) >>> 0, hasFs: fs !== 'nofs', b };
}).sort((x, y) => x.code - y.code || x.size - y.size || x.fs - y.fs);
const parts = [];
const ENTRY = 48;
let at = 12 + entries.length * ENTRY;
const index = Buffer.alloc(at);
index.write('LPTP', 0, 'latin1');
index.writeUInt32BE(PATCH_TABLE_VERSION, 4);
index.writeUInt32BE(entries.length, 8);
const runsAt = [], namesAt = [];
for (const e of entries) {
  runsAt.push(at);
  const head = Buffer.alloc(4); head.writeUInt32BE(e.b.runs.length);
  parts.push(head); at += 4;
  for (const [off, h] of e.b.runs) {
    const w = Buffer.from(h, 'hex');
    const rh = Buffer.alloc(8); rh.writeUInt32BE(off); rh.writeUInt32BE(w.length / 4, 4);
    parts.push(rh, w); at += 8 + w.length;
  }
}
for (const e of entries) {
  namesAt.push(at);
  const n = Buffer.from(e.b.names[0] + '\0', 'latin1');
  parts.push(n); at += n.length;
}
entries.forEach((e, i) => {
  const o = 12 + i * ENTRY, a = e.b.after;
  const [ac, , af] = a.key.split('-');
  index.writeUInt32BE(e.code, o); index.writeUInt32BE(e.size, o + 4); index.writeUInt32BE(e.fs, o + 8);
  index.writeUInt32BE((e.hasFs ? 1 : 0) | (e.b.keys ? 2 : 0), o + 12);
  index.writeUInt32BE(parseInt(ac, 16) >>> 0, o + 16); index.writeUInt32BE(af === 'nofs' ? 0 : parseInt(af, 16) >>> 0, o + 20);
  index.writeUInt32BE(runsAt[i], o + 24); index.writeUInt32BE(namesAt[i], o + 28);
  const { ir, power } = e.b.options || {};
  if (ir) { index.writeUInt32BE(ir[0], o + 32); index.writeUInt32BE(ir[1] >>> 0, o + 36); }
  if (power) { index.writeUInt32BE(power[0], o + 40); index.writeUInt32BE(power[1] >>> 0, o + 44); }
});
const bin = Buffer.concat([index, ...parts]);
writeFileSync(`${OUT}/sb_patches.bin`, bin);
writeFileSync(`${OUT}/sb_patches.S`, `// Generated by tools/picogen.mjs (do not edit): the patch table, sb_patches.bin. Assembled
// with this directory on the include path (-Wa,-I...), for .incbin. ELF (the Pico) or Mach-O
// (a Mac host build).
#ifdef __APPLE__
    .section __TEXT,__const
    .p2align 2
    .globl _sb_patches
    .globl _sb_patches_end
_sb_patches:
    .incbin "sb_patches.bin"
_sb_patches_end:
#else
    .section .rodata.sb_patches, "a"
    .balign 4
    .global sb_patches
    .global sb_patches_end
sb_patches:
    .incbin "sb_patches.bin"
sb_patches_end:
#endif
`);
console.log(`loader ${sent.length} bytes, stage 0 ${stage0.size}, tier 3 ${tier3.length}; patch table ${entries.length} builds, ${(bin.length / 1024).toFixed(0)} KB -> ${OUT}/`);
