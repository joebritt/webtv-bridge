// The Bridge's web page into the firmware: pico/web/page.html with page.css and the script
// inlined, gzipped (web.c sends it with Content-Encoding: gzip). The script is the modules the
// page uses (web/wtvdisk.js, src/machine/solo_cels.js, web/boxscreen.js, web/irkeys.js), each in a scope of its
// own with its exports made page-wide constants (its imports are the earlier ones' exports),
// then pico/web/page.js.
//
//   node tools/webgen.mjs        writes pico/src/gen/web_page.h and web_page.c
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const OUT = join(ROOT, 'pico/src/gen');

const MODULES = ['web/wtvdisk.js', 'src/machine/solo_cels.js', 'web/boxscreen.js', 'web/irkeys.js'];
const inline = (path) => {
  let src = read(path).replace(/^import .*$/gm, '');
  if (/^export (const|let) \w+ = [^;\n]*, \w+ = /m.test(src)) throw new Error(`${path}: one export to a declaration, please`);
  const names = [];
  src = src.replace(/^export (async function|function|class|const|let) (\w+)/gm, (_, kind, name) => { names.push(name); return `${kind} ${name}`; });
  src = src.replace(/^export \{([^}]*)\};?$/gm, (_, list) => { names.push(...list.split(',').map((n) => n.trim()).filter(Boolean)); return ''; });
  return `// ${path}\nconst { ${names.join(', ')} } = (() => {\n${src}\nreturn { ${names.join(', ')} };\n})();\n`;
};
const script = MODULES.map(inline).join('\n') + '\n' + read('pico/web/page.js');
if (script.includes('</script')) throw new Error('the script mentions </script>');
const html = read('pico/web/page.html')
  .replace('/*STYLE*/', () => read('pico/web/page.css'))
  .replace('/*SCRIPT*/', () => script);
const gz = gzipSync(Buffer.from(html), { level: 9 });

writeFileSync(join(OUT, 'web_page.h'), `// Generated by tools/webgen.mjs from pico/web/ and the modules it inlines (do not edit).
#pragma once
#include <stdint.h>
#include <stddef.h>

extern const uint8_t web_page_gz[];      // the page, gzipped (${html.length} bytes as HTML)
extern const size_t web_page_gz_len;
`);
const rows = [];
for (let i = 0; i < gz.length; i += 20) rows.push('    ' + [...gz.subarray(i, i + 20)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(','));
writeFileSync(join(OUT, 'web_page.c'), `// Generated by tools/webgen.mjs from pico/web/ and the modules it inlines (do not edit).
#include "web_page.h"

const uint8_t web_page_gz[${gz.length}] = {
${rows.join(',\n')}
};
const size_t web_page_gz_len = sizeof web_page_gz;
`);
console.log(`pico/src/gen/web_page.c: ${html.length} bytes of HTML, ${gz.length} gzipped`);
