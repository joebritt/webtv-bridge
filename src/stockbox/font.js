export const FIRST = 0x20, LAST = 0x7e;

export const FONT = new Uint8Array((LAST - FIRST + 1) * 8);
for (let c = FIRST; c <= LAST; c++) {
  const rows = (G[String.fromCharCode(c)] ?? '').split(' ').filter(Boolean);
  rows.forEach((r, i) => {
    let b = 0;
    for (let x = 0; x < 5; x++) if (r[x] === '#') b |= 0x80 >> x;
    FONT[(c - FIRST) * 8 + i] = b;
  });
}
